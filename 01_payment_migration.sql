-- JJCC Railways: payment and cancellation migration
-- Run this in Supabase SQL Editor AFTER taking a database backup.
-- Existing bookings are retained. Existing confirmed bookings remain confirmed.

ALTER TABLE public.bookings
  ADD COLUMN IF NOT EXISTS payment_deadline_at timestamptz,
  ADD COLUMN IF NOT EXISTS paid_at timestamptz,
  ADD COLUMN IF NOT EXISTS cancelled_at timestamptz;

CREATE TABLE IF NOT EXISTS public.booking_payments (
  payment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id bigint NOT NULL REFERENCES public.bookings(booking_id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  provider varchar(30) NOT NULL DEFAULT 'paypal',
  provider_order_id text UNIQUE,
  provider_capture_id text UNIQUE,
  amount numeric(10,2) NOT NULL CHECK (amount >= 0),
  currency varchar(3) NOT NULL DEFAULT 'PHP',
  payment_status varchar(20) NOT NULL DEFAULT 'created'
    CHECK (payment_status IN ('created','approved','completed','failed','refunded')),
  created_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS booking_payments_booking_id_idx
  ON public.booking_payments(booking_id);
CREATE INDEX IF NOT EXISTS bookings_payment_deadline_idx
  ON public.bookings(payment_deadline_at)
  WHERE booking_status = 'pending_payment';

ALTER TABLE public.booking_payments ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Users can view their own booking payments" ON public.booking_payments;
CREATE POLICY "Users can view their own booking payments"
  ON public.booking_payments FOR SELECT TO authenticated
  USING (user_id = auth.uid());
-- Inserts and updates are performed only by trusted Edge Functions using service role.

-- New bookings are pending payment. Existing booking rows are not modified.
CREATE OR REPLACE FUNCTION public.set_booking_pending_payment()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    -- Only change the default/legacy confirmed status for newly inserted bookings.
    IF NEW.booking_status IS NULL OR lower(NEW.booking_status) = 'confirmed' THEN
      NEW.booking_status := 'pending_payment';
      NEW.payment_deadline_at := COALESCE(NEW.payment_deadline_at, now() + interval '10 minutes');
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_set_booking_pending_payment ON public.bookings;
CREATE TRIGGER trg_set_booking_pending_payment
BEFORE INSERT ON public.bookings
FOR EACH ROW EXECUTE FUNCTION public.set_booking_pending_payment();

-- Enforce cancellation cutoff at database level, including calls through cancel_booking RPC.
CREATE OR REPLACE FUNCTION public.enforce_booking_cancellation_window()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  v_departure timestamptz;
BEGIN
  IF lower(COALESCE(NEW.booking_status,'')) = 'cancelled'
     AND lower(COALESCE(OLD.booking_status,'')) <> 'cancelled' THEN
    v_departure := (NEW.travel_date + NEW.departure_time) AT TIME ZONE 'Asia/Manila';
    IF v_departure <= now() + interval '24 hours' THEN
      RAISE EXCEPTION 'Cancellation is allowed only until 24 hours before departure.';
    END IF;
    NEW.cancelled_at := COALESCE(NEW.cancelled_at, now());
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_enforce_booking_cancellation_window ON public.bookings;
CREATE TRIGGER trg_enforce_booking_cancellation_window
BEFORE UPDATE OF booking_status ON public.bookings
FOR EACH ROW EXECUTE FUNCTION public.enforce_booking_cancellation_window();

-- Expire unpaid bookings. Their status is excluded from the seat/capacity checks below.
CREATE OR REPLACE FUNCTION public.expire_pending_bookings()
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE v_count integer;
BEGIN
  UPDATE public.bookings
     SET booking_status = 'expired'
   WHERE booking_status = 'pending_payment'
     AND payment_deadline_at IS NOT NULL
     AND payment_deadline_at <= now();
  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN v_count;
END;
$$;
GRANT EXECUTE ON FUNCTION public.expire_pending_bookings() TO service_role;

-- Patch existing public SQL functions that treat only cancelled/refunded as released.
-- This preserves their existing logic while also treating expired reservations as released.
DO $$
DECLARE r record; v_def text; v_new text;
BEGIN
  FOR r IN
    SELECT p.oid, n.nspname, p.proname, pg_get_function_identity_arguments(p.oid) AS args
    FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname = 'public' AND p.prokind = 'f'
  LOOP
    v_def := pg_get_functiondef(r.oid);
    v_new := replace(v_def,
      'NOT IN (''cancelled'', ''refunded'')',
      'NOT IN (''cancelled'', ''refunded'', ''expired'')');
    v_new := replace(v_new,
      'not in (''cancelled'', ''refunded'')',
      'not in (''cancelled'', ''refunded'', ''expired'')');
    IF v_new <> v_def THEN
      EXECUTE v_new;
    END IF;
  END LOOP;
END;
$$;

