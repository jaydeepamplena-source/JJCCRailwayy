-- JJCC Railways: combined one-time booking modification workflow.
-- Run AFTER 05_cancellation_policy_fix.sql. Back up Supabase first.
-- This migration adds request/payment records. It does not process real bank transfers.
-- Admins manually verify the uploaded receipt against amount_due before approval.

ALTER TABLE public.bookings
  ADD COLUMN IF NOT EXISTS modification_used boolean NOT NULL DEFAULT false;

CREATE TABLE IF NOT EXISTS public.booking_change_requests (
  request_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id bigint NOT NULL REFERENCES public.bookings(booking_id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  booking_reference text NOT NULL,
  requested_changes jsonb NOT NULL,
  amount_due numeric(10,2) NOT NULL CHECK (amount_due > 0),
  status text NOT NULL DEFAULT 'pending_payment'
    CHECK (status IN ('pending_payment','pending_review','approved','rejected','expired','cancelled')),
  payment_deadline_at timestamptz NOT NULL DEFAULT (now() + interval '10 minutes'),
  submitted_at timestamptz,
  reviewed_at timestamptz,
  reviewed_by uuid REFERENCES auth.users(id),
  admin_note text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.booking_change_payment_submissions (
  submission_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id bigint NOT NULL REFERENCES public.booking_change_requests(request_id) ON DELETE CASCADE,
  booking_id bigint NOT NULL REFERENCES public.bookings(booking_id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  receipt_path text NOT NULL,
  amount_due numeric(10,2) NOT NULL,
  status text NOT NULL DEFAULT 'pending_review'
    CHECK (status IN ('pending_review','approved','rejected')),
  admin_note text,
  submitted_at timestamptz NOT NULL DEFAULT now(),
  reviewed_at timestamptz,
  reviewed_by uuid REFERENCES auth.users(id)
);

CREATE INDEX IF NOT EXISTS booking_change_requests_user_idx
  ON public.booking_change_requests(user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS booking_change_requests_status_idx
  ON public.booking_change_requests(status, payment_deadline_at);
CREATE INDEX IF NOT EXISTS booking_change_payments_request_idx
  ON public.booking_change_payment_submissions(request_id, submitted_at DESC);

ALTER TABLE public.booking_change_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.booking_change_payment_submissions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Users read own booking change requests" ON public.booking_change_requests;
CREATE POLICY "Users read own booking change requests"
  ON public.booking_change_requests FOR SELECT TO authenticated
  USING (user_id = auth.uid());

DROP POLICY IF EXISTS "Staff read booking change requests" ON public.booking_change_requests;
CREATE POLICY "Staff read booking change requests"
  ON public.booking_change_requests FOR SELECT TO authenticated
  USING (public.current_user_role() IN ('admin','super_admin'));

DROP POLICY IF EXISTS "Users read own booking change receipts" ON public.booking_change_payment_submissions;
CREATE POLICY "Users read own booking change receipts"
  ON public.booking_change_payment_submissions FOR SELECT TO authenticated
  USING (user_id = auth.uid());

DROP POLICY IF EXISTS "Staff read booking change receipts" ON public.booking_change_payment_submissions;
CREATE POLICY "Staff read booking change receipts"
  ON public.booking_change_payment_submissions FOR SELECT TO authenticated
  USING (public.current_user_role() IN ('admin','super_admin'));

GRANT SELECT ON public.booking_change_requests TO authenticated;
GRANT SELECT ON public.booking_change_payment_submissions TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.booking_change_requests_request_id_seq TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.booking_change_payment_submissions_submission_id_seq TO authenticated;

CREATE OR REPLACE FUNCTION public.create_booking_change_request(
  p_booking_reference text,
  p_changes jsonb,
  p_amount_due numeric
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, auth AS $$
DECLARE
  v_user uuid := auth.uid();
  v_booking public.bookings%ROWTYPE;
  v_request_id bigint;
  v_passengers jsonb;
  v_date text;
  v_class text;
BEGIN
  IF v_user IS NULL THEN RAISE EXCEPTION 'Please sign in first.'; END IF;
  IF p_changes IS NULL OR jsonb_typeof(p_changes) <> 'object' THEN
    RAISE EXCEPTION 'Invalid modification details.';
  END IF;
  IF p_amount_due IS NULL OR p_amount_due <= 0 THEN
    RAISE EXCEPTION 'The additional payment amount must be greater than zero.';
  END IF;

  SELECT * INTO v_booking
    FROM public.bookings
   WHERE booking_reference = upper(btrim(p_booking_reference))
     AND user_id = v_user
   FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Booking not found.'; END IF;
  IF lower(v_booking.booking_status) <> 'confirmed' THEN
    RAISE EXCEPTION 'Only confirmed bookings can be modified.';
  END IF;
  IF v_booking.modification_used THEN
    RAISE EXCEPTION 'This booking has already used its one allowed modification.';
  END IF;
  IF ((v_booking.travel_date + v_booking.departure_time) AT TIME ZONE 'Asia/Manila') <= now() THEN
    RAISE EXCEPTION 'This booking can no longer be modified after departure.';
  END IF;

  UPDATE public.booking_change_requests
     SET status = 'expired', updated_at = now()
   WHERE booking_id = v_booking.booking_id
     AND status = 'pending_payment'
     AND payment_deadline_at <= now();

  IF EXISTS (
    SELECT 1 FROM public.booking_change_requests
     WHERE booking_id = v_booking.booking_id
       AND status IN ('pending_payment','pending_review','rejected')
       AND payment_deadline_at > now()
  ) THEN
    RAISE EXCEPTION 'There is already an active modification request for this booking.';
  END IF;

  v_date := NULLIF(p_changes->>'travel_date','');
  v_class := NULLIF(p_changes->>'booking_class','');
  v_passengers := COALESCE(p_changes->'passengers','[]'::jsonb);

  IF jsonb_typeof(v_passengers) <> 'array' OR jsonb_array_length(v_passengers) > 1 THEN
    RAISE EXCEPTION 'Only one additional passenger can be included in a modification.';
  END IF;
  IF v_date IS NULL AND v_class IS NULL AND jsonb_array_length(v_passengers) = 0 THEN
    RAISE EXCEPTION 'Select at least one modification.';
  END IF;
  IF v_date IS NOT NULL THEN
    PERFORM v_date::date;
    IF v_date::date <= (now() AT TIME ZONE 'Asia/Manila')::date THEN RAISE EXCEPTION 'New travel date must be in the future.'; END IF;
    IF v_date::date = v_booking.travel_date THEN RAISE EXCEPTION 'The selected travel date is unchanged.'; END IF;
  END IF;
  IF v_class IS NOT NULL AND v_class NOT IN ('First Class') THEN
    RAISE EXCEPTION 'The selected class upgrade is not available.';
  END IF;
  IF v_class = COALESCE(v_booking.booking_class,'Standard') THEN
    RAISE EXCEPTION 'The booking is already in the selected class.';
  END IF;
  IF jsonb_array_length(v_passengers) > 0 THEN
    IF COALESCE(btrim(v_passengers->0->>'full_name'),'') = '' THEN
      RAISE EXCEPTION 'Additional passenger name is required.';
    END IF;
  END IF;

  INSERT INTO public.booking_change_requests
    (booking_id,user_id,booking_reference,requested_changes,amount_due,status,payment_deadline_at)
  VALUES
    (v_booking.booking_id,v_user,v_booking.booking_reference,p_changes,p_amount_due,
     'pending_payment',now()+interval '10 minutes')
  RETURNING request_id INTO v_request_id;

  RETURN jsonb_build_object(
    'request_id',v_request_id,
    'booking_reference',v_booking.booking_reference,
    'amount_due',p_amount_due,
    'status','pending_payment',
    'payment_deadline_at',now()+interval '10 minutes'
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.submit_booking_change_receipt(
  p_request_id bigint,
  p_receipt_path text
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, auth AS $$
DECLARE
  v_user uuid := auth.uid();
  v_request public.booking_change_requests%ROWTYPE;
  v_submission_id bigint;
BEGIN
  IF v_user IS NULL THEN RAISE EXCEPTION 'Please sign in first.'; END IF;
  IF COALESCE(btrim(p_receipt_path),'') = '' THEN RAISE EXCEPTION 'Receipt path is required.'; END IF;
  IF split_part(p_receipt_path,'/',1) <> v_user::text THEN
    RAISE EXCEPTION 'Receipt path must belong to your signed-in account.';
  END IF;

  SELECT * INTO v_request
    FROM public.booking_change_requests
   WHERE request_id = p_request_id AND user_id = v_user
   FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Modification request not found.'; END IF;
  IF v_request.status NOT IN ('pending_payment','rejected') THEN
    RAISE EXCEPTION 'This modification request is not accepting a receipt.';
  END IF;
  IF v_request.payment_deadline_at <= now() THEN
    UPDATE public.booking_change_requests SET status='expired',updated_at=now()
     WHERE request_id=v_request.request_id;
    RAISE EXCEPTION 'The 10-minute modification payment deadline has expired.';
  END IF;
  IF EXISTS (
    SELECT 1 FROM public.booking_change_payment_submissions
     WHERE request_id=v_request.request_id AND status='pending_review'
  ) THEN
    RAISE EXCEPTION 'A receipt is already awaiting administrator review.';
  END IF;

  INSERT INTO public.booking_change_payment_submissions
    (request_id,booking_id,user_id,receipt_path,amount_due,status)
  VALUES
    (v_request.request_id,v_request.booking_id,v_user,p_receipt_path,v_request.amount_due,'pending_review')
  RETURNING submission_id INTO v_submission_id;

  UPDATE public.booking_change_requests
     SET status='pending_review',submitted_at=now(),updated_at=now()
   WHERE request_id=v_request.request_id;

  RETURN jsonb_build_object('success',true,'submission_id',v_submission_id,'status','pending_review');
END;
$$;

CREATE OR REPLACE FUNCTION public.review_booking_change_request(
  p_submission_id bigint,
  p_decision text,
  p_admin_note text DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, auth AS $$
DECLARE
  v_role text := public.current_user_role();
  v_reviewer uuid := auth.uid();
  v_submission public.booking_change_payment_submissions%ROWTYPE;
  v_request public.booking_change_requests%ROWTYPE;
  v_booking public.bookings%ROWTYPE;
  v_passenger jsonb;
  v_title text;
  v_message text;
BEGIN
  IF COALESCE(v_role,'') NOT IN ('admin','super_admin') THEN
    RAISE EXCEPTION 'Only an administrator can review modification payments.';
  END IF;
  IF p_decision NOT IN ('approved','rejected') THEN RAISE EXCEPTION 'Invalid review decision.'; END IF;

  SELECT * INTO v_submission FROM public.booking_change_payment_submissions
   WHERE submission_id=p_submission_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Modification receipt not found.'; END IF;
  IF v_submission.status <> 'pending_review' THEN RAISE EXCEPTION 'This receipt has already been reviewed.'; END IF;

  SELECT * INTO v_request FROM public.booking_change_requests
   WHERE request_id=v_submission.request_id FOR UPDATE;
  SELECT * INTO v_booking FROM public.bookings
   WHERE booking_id=v_request.booking_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Original booking not found.'; END IF;

  IF p_decision='approved' THEN
    IF v_request.status <> 'pending_review'
       OR v_submission.submitted_at > v_request.payment_deadline_at THEN
      RAISE EXCEPTION 'This modification payment was not submitted within the 10-minute deadline.';
    END IF;
    IF v_booking.booking_status <> 'confirmed' OR v_booking.modification_used THEN
      RAISE EXCEPTION 'The original booking is no longer eligible for modification.';
    END IF;

    -- Permit the protected legacy RPCs only inside this staff-approved transaction.
    PERFORM set_config('jjcc.allow_booking_modification','on',true);
    -- The legacy booking RPCs are owner-scoped; execute them in the request owner's
    -- authenticated context, then restore the reviewing administrator.
    PERFORM set_config('request.jwt.claim.sub',v_request.user_id::text,true);

    -- Apply every selected change in the same database transaction.
    IF NULLIF(v_request.requested_changes->>'travel_date','') IS NOT NULL THEN
      PERFORM public.change_booking_travel_date(
        v_booking.booking_reference,
        (v_request.requested_changes->>'travel_date')::date
      );
    END IF;

    IF NULLIF(v_request.requested_changes->>'booking_class','') IS NOT NULL THEN
      PERFORM public.upgrade_booking_class(
        v_booking.booking_reference,
        v_request.requested_changes->>'booking_class'
      );
    END IF;

    FOR v_passenger IN
      SELECT value FROM jsonb_array_elements(COALESCE(v_request.requested_changes->'passengers','[]'::jsonb))
    LOOP
      PERFORM public.add_passenger_to_booking(
        v_booking.booking_reference,
        v_passenger->>'full_name',
        NULLIF(v_passenger->>'age','')::integer,
        COALESCE(NULLIF(v_passenger->>'passenger_type',''),'adult')
      );
    END LOOP;

    PERFORM set_config('request.jwt.claim.sub',v_reviewer::text,true);

    UPDATE public.bookings
       SET modification_used=true
     WHERE booking_id=v_booking.booking_id;

    UPDATE public.booking_change_requests
       SET status='approved',reviewed_at=now(),reviewed_by=v_reviewer,
           admin_note=NULLIF(btrim(p_admin_note),''),updated_at=now()
     WHERE request_id=v_request.request_id;
    v_title := 'Booking modification approved';
    v_message := 'Your combined modification for booking '||v_booking.booking_reference||' was approved and applied.';
  ELSE
    UPDATE public.booking_change_requests
       SET status=CASE WHEN payment_deadline_at>now() THEN 'rejected' ELSE 'expired' END,
           reviewed_at=now(),reviewed_by=v_reviewer,
           admin_note=NULLIF(btrim(p_admin_note),''),updated_at=now()
     WHERE request_id=v_request.request_id;
    v_title := 'Booking modification payment rejected';
    v_message := 'Your modification receipt for booking '||v_booking.booking_reference||' was rejected. '||
      COALESCE(NULLIF(btrim(p_admin_note),''),'Please check the receipt and try again before the payment deadline.');
  END IF;

  UPDATE public.booking_change_payment_submissions
     SET status=p_decision,admin_note=NULLIF(btrim(p_admin_note),''),
         reviewed_at=now(),reviewed_by=v_reviewer
   WHERE submission_id=p_submission_id;

  INSERT INTO public.user_notifications(user_id,booking_id,title,message,notification_type)
  VALUES (v_request.user_id,v_request.booking_id,v_title,v_message,
          CASE WHEN p_decision='approved' THEN 'success' ELSE 'warning' END);

  RETURN jsonb_build_object('success',true,'decision',p_decision,'request_id',v_request.request_id);
END;
$$;

CREATE OR REPLACE FUNCTION public.cancel_booking_change_request(p_request_id bigint)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, auth AS $$
DECLARE v_user uuid:=auth.uid(); v_req public.booking_change_requests%ROWTYPE;
BEGIN
  SELECT * INTO v_req FROM public.booking_change_requests
   WHERE request_id=p_request_id AND user_id=v_user FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Modification request not found.'; END IF;
  IF v_req.status NOT IN ('pending_payment','rejected') THEN
    RAISE EXCEPTION 'Only an unpaid modification request can be cancelled.';
  END IF;
  UPDATE public.booking_change_requests SET status='cancelled',updated_at=now()
   WHERE request_id=p_request_id;
  RETURN jsonb_build_object('success',true,'status','cancelled');
END;
$$;

CREATE OR REPLACE FUNCTION public.expire_booking_change_requests()
RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_count integer;
BEGIN
  UPDATE public.booking_change_requests
     SET status='expired',updated_at=now()
   WHERE status IN ('pending_payment','rejected') AND payment_deadline_at<=now();
  GET DIAGNOSTICS v_count=ROW_COUNT;
  RETURN v_count;
END;
$$;

