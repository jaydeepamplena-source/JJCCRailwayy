-- Prevent users from bypassing the combined workflow by calling the older
-- date/class/passenger RPCs directly. Only the review RPC sets this
-- transaction-local flag while applying an approved combined request.
CREATE OR REPLACE FUNCTION public.guard_confirmed_booking_modification()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
BEGIN
  IF lower(COALESCE(OLD.booking_status,''))='confirmed'
     AND (
       NEW.travel_date IS DISTINCT FROM OLD.travel_date OR
       NEW.booking_class IS DISTINCT FROM OLD.booking_class OR
       NEW.total_passengers IS DISTINCT FROM OLD.total_passengers OR
       NEW.total_fare IS DISTINCT FROM OLD.total_fare
     )
     AND COALESCE(current_setting('jjcc.allow_booking_modification',true),'off') <> 'on' THEN
    RAISE EXCEPTION 'Confirmed booking changes must use the combined modification request and Admin approval workflow.';
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_guard_confirmed_booking_modification ON public.bookings;
CREATE TRIGGER trg_guard_confirmed_booking_modification
BEFORE UPDATE OF travel_date,booking_class,total_passengers,total_fare ON public.bookings
FOR EACH ROW EXECUTE FUNCTION public.guard_confirmed_booking_modification();

CREATE OR REPLACE FUNCTION public.guard_confirmed_booking_passenger_link()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_booking_id bigint; v_status text;
BEGIN
  v_booking_id := CASE WHEN TG_OP='DELETE' THEN OLD.booking_id ELSE NEW.booking_id END;
  SELECT booking_status INTO v_status FROM public.bookings WHERE booking_id=v_booking_id;
  IF lower(COALESCE(v_status,''))='confirmed'
     AND COALESCE(current_setting('jjcc.allow_booking_modification',true),'off') <> 'on' THEN
    RAISE EXCEPTION 'Confirmed booking passenger changes must use the combined modification request and Admin approval workflow.';
  END IF;
  IF TG_OP='DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
END;
$$;
DROP TRIGGER IF EXISTS trg_guard_confirmed_booking_passenger_link ON public.booking_passengers;
CREATE TRIGGER trg_guard_confirmed_booking_passenger_link
BEFORE INSERT OR UPDATE OR DELETE ON public.booking_passengers
FOR EACH ROW EXECUTE FUNCTION public.guard_confirmed_booking_passenger_link();

-- If the original booking is cancelled, any unpaid/unreviewed modification draft is closed.
CREATE OR REPLACE FUNCTION public.close_booking_change_requests_on_cancellation()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
BEGIN
  IF lower(COALESCE(NEW.booking_status,''))='cancelled'
     AND lower(COALESCE(OLD.booking_status,''))<>'cancelled' THEN
    UPDATE public.booking_change_requests
       SET status='cancelled',updated_at=now()
     WHERE booking_id=NEW.booking_id
       AND status IN ('pending_payment','pending_review','rejected');
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_close_booking_change_requests_on_cancellation ON public.bookings;
CREATE TRIGGER trg_close_booking_change_requests_on_cancellation
AFTER UPDATE OF booking_status ON public.bookings
FOR EACH ROW EXECUTE FUNCTION public.close_booking_change_requests_on_cancellation();

