-- Admins maintain train condition through a role-checked RPC, not direct table writes.
CREATE OR REPLACE FUNCTION public.set_train_status(p_train_id bigint, p_status text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_role text;
BEGIN
  v_role := public.current_user_role();
  IF COALESCE(v_role,'') NOT IN ('admin','super_admin') THEN
    RAISE EXCEPTION 'Only an administrator can update train status.';
  END IF;
  IF COALESCE(p_status,'') NOT IN ('active','broken','inactive') THEN
    RAISE EXCEPTION 'Invalid train status.';
  END IF;
  UPDATE public.trains SET train_status = p_status WHERE train_id = p_train_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Train not found.'; END IF;
  RETURN jsonb_build_object('success',true,'train_id',p_train_id,'train_status',p_status);
END;
$$;
REVOKE ALL ON FUNCTION public.set_train_status(bigint,text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.set_train_status(bigint,text) TO authenticated;

