-- New reservations hold their seats for 10 minutes while receipt is uploaded.
CREATE OR REPLACE FUNCTION public.set_booking_pending_payment()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.booking_status IS NULL OR lower(NEW.booking_status) IN ('confirmed','pending_payment') THEN
      NEW.booking_status := 'pending_payment';
      NEW.payment_deadline_at := COALESCE(NEW.payment_deadline_at, now() + interval '10 minutes');
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.expire_pending_bookings()
RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_count integer;
BEGIN
  UPDATE public.bookings AS b
     SET booking_status = 'expired'
   WHERE b.booking_status = 'pending_payment'
     AND b.payment_deadline_at IS NOT NULL
     AND b.payment_deadline_at <= now()
     AND NOT EXISTS (SELECT 1 FROM public.payment_submissions ps WHERE ps.booking_id = b.booking_id AND ps.status = 'pending_review');
  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN v_count;
END;
$$;
REVOKE ALL ON FUNCTION public.expire_pending_bookings() FROM PUBLIC, authenticated;
GRANT EXECUTE ON FUNCTION public.expire_pending_bookings() TO service_role;

-- Staff-only approval/rejection. Approval is the only action that confirms a booking.
CREATE OR REPLACE FUNCTION public.review_payment_submission(
  p_submission_id bigint,
  p_decision text,
  p_admin_note text DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, auth AS $$
DECLARE
  v_role text;
  v_submission public.payment_submissions%ROWTYPE;
  v_booking public.bookings%ROWTYPE;
  v_title text;
  v_message text;
BEGIN
  v_role := public.current_user_role();
  IF COALESCE(v_role,'') NOT IN ('admin','super_admin') THEN
    RAISE EXCEPTION 'Only an administrator can review receipts.';
  END IF;
  IF COALESCE(p_decision,'') NOT IN ('approved','rejected') THEN
    RAISE EXCEPTION 'Decision must be approved or rejected.';
  END IF;

  SELECT * INTO v_submission FROM public.payment_submissions
   WHERE submission_id = p_submission_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Receipt submission not found.'; END IF;
  IF v_submission.status <> 'pending_review' THEN
    RAISE EXCEPTION 'This receipt has already been reviewed.';
  END IF;

  SELECT * INTO v_booking FROM public.bookings
   WHERE booking_id = v_submission.booking_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Booking not found.'; END IF;

  IF p_decision = 'approved' THEN
    IF v_booking.booking_status <> 'pending_payment'
       OR v_booking.payment_deadline_at IS NULL
       OR v_submission.submitted_at > v_booking.payment_deadline_at THEN
      RAISE EXCEPTION 'This receipt was submitted after the 10-minute reservation hold expired; this booking cannot be approved.';
    END IF;
    UPDATE public.bookings
       SET booking_status = 'confirmed',
           paid_at = COALESCE(paid_at, now())
     WHERE booking_id = v_booking.booking_id;

    -- Keep the existing booking_payments table in sync with the approved receipt.
    -- Update the newest payment row if one exists; otherwise create a manual-review record.
    UPDATE public.booking_payments
       SET payment_status = 'completed',
           amount = v_booking.total_fare,
           currency = COALESCE(currency, 'PHP'),
           completed_at = COALESCE(completed_at, now()),
           updated_at = now()
     WHERE payment_id = (
       SELECT bp.payment_id
         FROM public.booking_payments bp
        WHERE bp.booking_id = v_booking.booking_id
        ORDER BY bp.created_at DESC, bp.payment_id DESC
        LIMIT 1
     );

    IF NOT FOUND THEN
      INSERT INTO public.booking_payments
        (booking_id, user_id, provider, amount, currency, payment_status, completed_at, updated_at)
      VALUES
        (v_booking.booking_id, v_submission.user_id, 'manual_receipt',
         v_booking.total_fare, 'PHP', 'completed', now(), now());
    END IF;

    v_title := 'Payment approved';
    v_message := 'Your receipt was approved. Your booking ' || v_booking.booking_reference || ' is now confirmed.';
  ELSE
    v_title := 'Payment receipt not approved';
    v_message := 'Your receipt for booking ' || v_booking.booking_reference || ' was not approved. ' ||
      COALESCE(NULLIF(btrim(p_admin_note),''), 'Please review the receipt and contact support if you need help.') ||
      ' Your 10-minute seat hold still applies; upload a corrected receipt before the deadline if it has not expired.';
  END IF;

  UPDATE public.payment_submissions
     SET status = p_decision, admin_note = NULLIF(btrim(p_admin_note),''),
         reviewed_at = now(), reviewed_by = auth.uid()
   WHERE submission_id = p_submission_id;

  INSERT INTO public.user_notifications(user_id, booking_id, title, message, notification_type)
  VALUES (v_submission.user_id, v_submission.booking_id, v_title, v_message,
          CASE WHEN p_decision = 'approved' THEN 'success' ELSE 'warning' END);

  RETURN jsonb_build_object('success', true, 'decision', p_decision,
    'booking_reference', v_booking.booking_reference);
END;
$$;
REVOKE ALL ON FUNCTION public.review_payment_submission(bigint,text,text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.review_payment_submission(bigint,text,text) TO authenticated;

