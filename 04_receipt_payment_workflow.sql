CREATE OR REPLACE FUNCTION public.set_payment_submission_snapshot()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_reference text; v_fare numeric(10,2); v_date date;
BEGIN
  SELECT b.booking_reference, b.total_fare, b.travel_date
    INTO v_reference, v_fare, v_date
    FROM public.bookings b
   WHERE b.booking_id = NEW.booking_id AND b.user_id = NEW.user_id;
  IF v_reference IS NULL THEN
    RAISE EXCEPTION 'Booking not found for this account.';
  END IF;
  NEW.booking_reference := v_reference;
  NEW.total_fare := v_fare;
  NEW.travel_date := v_date;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_payment_submission_snapshot ON public.payment_submissions;
CREATE TRIGGER trg_payment_submission_snapshot
BEFORE INSERT ON public.payment_submissions
FOR EACH ROW EXECUTE FUNCTION public.set_payment_submission_snapshot();

